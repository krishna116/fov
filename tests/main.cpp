#include "FovComputer.h"

#define TB_IMPL
#include "termbox2.h"

int main(void) {
  const int w = 24;
  const int h = 18;
  int gameMap[h][w]={
    '#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#',
    '#','.','.','.','.','#','.','.','.','.','.','.','.','.','.','.','#','.','.','.','#','.','.','#',
    '#','.','.','.','.','#','.','.','.','.','.','.','.','.','.','.','.','.','.','.','#','.','.','#',
    '#','.','.','.','.','.','.','.','.','.','.','.','#','.','.','.','#','#','.','.','#','#','.','#',
    '#','.','.','.','#','#','#','#','.','.','.','#','#','.','.','.','.','.','.','.','.','.','.','#',
    '#','#','#','.','.','.','#','.','.','.','.','.','.','.','.','#','.','.','.','.','.','.','.','#',
    '#','.','.','.','.','.','#','.','.','.','.','.','.','#','.','#','.','.','.','.','.','.','.','#',
    '#','.','#','.','.','.','.','.','.','.','#','#','#','#','.','#','.','.','.','.','.','.','.','#',
    '#','.','#','.','.','.','.','.','.','.','.','.','.','#','.','#','.','#','#','#','#','.','.','#',
    '#','.','#','.','.','.','#','#','.','#','.','#','.','.','.','#','.','.','.','.','.','.','.','#',
    '#','.','#','.','.','.','.','.','.','.','.','.','.','.','.','#','.','.','.','.','.','.','.','#',
    '#','.','.','.','.','.','.','.','.','.','.','.','.','.','.','#','.','.','.','.','.','.','.','#',
    '#','.','#','.','.','.','.','.','.','.','.','.','.','.','.','#','#','.','#','#','#','#','#','#',
    '#','.','#','#','#','#','.','.','.','#','.','.','#','#','.','#','.','.','#','.','.','.','.','#',
    '#','.','.','.','.','.','.','.','#','#','#','.','#','#','.','.','.','.','#','.','.','.','.','#',
    '#','.','.','.','.','.','.','.','.','#','.','.','#','.','.','.','.','.','.','.','.','.','.','#',
    '#','.','.','#','.','.','.','.','.','.','.','.','#','#','.','.','.','.','#','.','.','.','.','#',
    '#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#','#'
  };

  bool lightMap[h][w];
  auto clearLightMap = [&]() {
    for (int y = 0; y < h; ++y) {
      for (int x = 0; x < w; ++x) {
        lightMap[y][x] = false;
      }
    }
  };

  auto isWall = [&](int x, int y) {
    if (0 <= x && x < w && 0 <= y && y < h) {
      return gameMap[y][x] == '#';
    }
    return true;
  };

  auto markVisible = [&](int x, int y) { lightMap[y][x] = true; };

  auto showGameMap = [&]() {
    for (int y = 0; y < h; ++y) {
      for (int x = 0; x < w; ++x) {
        int color = lightMap[y][x] ? TB_WHITE | TB_BRIGHT : TB_BLACK | TB_BRIGHT;
        tb_set_cell(x, y, gameMap[y][x], color, TB_DEFAULT);
      }
    }
  };

  // The hero.
  int heroX = 1;
  int heroY = 1;
  const int hero = '@';

  auto showHero = [&]() {
    tb_set_cell(heroX, heroY, hero, TB_YELLOW | TB_BRIGHT, TB_DEFAULT);
  };

  if (tb_init() != TB_OK)
    return 1;

  struct tb_event ev;
  while (true) {
    tb_poll_event(&ev);

    if (ev.key == TB_KEY_ARROW_UP) {
      if (!isWall(heroX, heroY - 1))
        heroY -= 1;
    } else if (ev.key == TB_KEY_ARROW_DOWN) {
      if (!isWall(heroX, heroY + 1))
        heroY += 1;
    } else if (ev.key == TB_KEY_ARROW_LEFT) {
      if (!isWall(heroX - 1, heroY))
        heroX -= 1;
    } else if (ev.key == TB_KEY_ARROW_RIGHT) {
      if (!isWall(heroX + 1, heroY))
        heroX += 1;
    } else if (ev.ch == 'q' || ev.ch == 'Q') {
      break;
    }

    tb_clear();
    clearLightMap();
    krishna::FovComputer::ComputeFov(heroX, heroY, isWall, markVisible, 6);
    showGameMap();
    showHero();
    tb_present();
  }

  tb_shutdown();

  return 0;
}